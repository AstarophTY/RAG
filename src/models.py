"""Pydantic data models for the RAG Against the Machine project.

This module defines all data models used throughout the RAG pipeline,
ensuring type safety and automatic validation at every boundary.
"""

import uuid
from typing import Union

from pydantic import BaseModel, Field


class MinimalSource(BaseModel):
    """Represents a minimal source location within a file.

    Attributes:
        file_path: Path to the source file.
        first_character_index: Starting character offset in the file.
        last_character_index: Ending character offset in the file.
    """

    file_path: str
    first_character_index: int
    last_character_index: int


class UnansweredQuestion(BaseModel):
    """Represents a question without an answer or sources.

    Attributes:
        question_id: Unique identifier, auto-generated as UUID4.
        question: The natural language question text.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """Represents a question with its ground truth answer and sources.

    Inherits from UnansweredQuestion and adds sources and answer.

    Attributes:
        sources: list of source locations that support the answer.
        answer: The ground truth answer string.
    """

    sources: list[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """Represents a dataset of RAG questions (answered or unanswered).

    Attributes:
        rag_questions: Mixed list of answered and unanswered questions.
    """

    rag_questions: list[Union[AnsweredQuestion, UnansweredQuestion]]


class MinimalSearchResults(BaseModel):
    """Represents the retrieval results for a single question.

    Attributes:
        question_id: Identifier matching the original question.
        question: The natural language question text.
        retrieved_sources: Ranked list of retrieved source locations.
    """

    question_id: str
    question: str
    retrieved_sources: list[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Represents retrieval results plus a generated answer.

    Inherits from MinimalSearchResults and adds the generated answer.

    Attributes:
        answer: The answer generated by the LLM from retrieved context.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Represents the full search output for a dataset.

    Attributes:
        search_results: list of per-question retrieval results.
        k: Number of sources retrieved per question.
    """

    search_results: list[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(StudentSearchResults):
    """Represents the full search + answer output for a dataset.

    Inherits from StudentSearchResults and overrides search_results
    with MinimalAnswer objects that include generated answers.

    Attributes:
        search_results: list of per-question results with answers.
    """

    search_results: list[MinimalAnswer]  # type: ignore[assignment]
